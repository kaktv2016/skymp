import {test} from 'node:test';
import a from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {spawnSync} from 'node:child_process';
import {Client} from '@modelcontextprotocol/client';
import {StdioClientTransport} from '@modelcontextprotocol/client/stdio';
const pkg=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const repo=path.resolve(pkg,'../../..');
test('actual MCP initializes, discovers, inspects real source and authors verified scratch ESP',async()=>{
 const work=fs.mkdtempSync(path.join(repo,'build/rp-audit/creation-kit-mcp/test-'));
 const client=new Client({name:'frostveil-verification',version:'1'});
 const transport=new StdioClientTransport({command:process.execPath,args:[path.join(pkg,'dist/index.js')],env:{...process.env,FROSTVEIL_CK_WORK:work},stderr:'pipe'});
 let stderr='';transport.stderr?.on('data',b=>stderr+=b);
 try {
  await client.connect(transport);
  const tools=await client.listTools();a.ok(tools.tools.some(t=>t.name==='ck_create_npc'));
  const called=new Set(),progress=[];
  const call=async(name,args={},options)=>{called.add(name);const r=await client.callTool({name,arguments:args},options);a.ok(!r.isError,JSON.stringify(r));return JSON.parse(r.content[0].text);};
  const caps=await call('ck_capabilities',{}, {onprogress:p=>progress.push(p.progress)});a.equal(caps.facegen,'MANUAL_REQUIRED');a.deepEqual(progress,[0,2]);
  a.equal((await call('ck_inspect_installation')).creationKit,'1.7.99.0');
  a.ok((await call('ck_list_plugins')).plugins.includes('FrostveilNPCTest.esp'));
  const source=await call('ck_list_npcs',{plugin:'FrostveilNPCTest.esp'});a.equal(source.npcs.filter(n=>!n.deleted).length,2);
  const info=await call('ck_get_npc',{plugin:'FrostveilNPCTest.esp',localId:0x5901});a.equal(info.npc.editorId,'FV_GuildClerk_Test');
  a.equal((await call('ck_list_outfits',{plugin:'FrostveilNPCTest.esp'})).outfits.length,2);
  a.equal((await call('ck_validate_plugin',{plugin:'FrostveilNPCTest.esp'})).valid,true);
  a.equal((await call('ck_validate_facegen',{plugin:'FrostveilNPCTest.esp',localId:0x5901})).valid,true);
  const plan=await call('ck_plan_npc_creation',{editorId:'FV_MCP_GuildMage',displayName:'Frostveil Guild Mage',height:1});
  const denied=await client.callTool({name:'ck_create_npc',arguments:{planId:plan.planId,reviewHash:'0'.repeat(64),operationId:'denied'}});a.equal(denied.isError,true);
  const args={planId:plan.planId,reviewHash:plan.reviewHash,operationId:'guild-mage'};
  const dry=await call('ck_create_npc',{...args,dryRun:true});a.equal(dry.status,'DRY_RUN');
  const created=await call('ck_create_npc',args);a.equal(created.status,'VERIFIED_STAGED');a.equal(created.backend,'MUTAGEN_HEADLESS');
  a.equal((await call('ck_create_npc',args)).sha256,created.sha256);
  const valid=await call('ck_validate_plugin',{plugin:created.plugin});a.equal(valid.valid,true);a.equal(valid.npcs.length,1);a.equal(valid.outfits.length,1);
  a.deepEqual(valid.masters,['Skyrim.esm']);a.equal(valid.npcs[0].sex,'female');
  const update=await call('ck_update_npc',{plugin:created.plugin,expectedSha256:created.sha256,displayName:'Frostveil Mage Revised',height:1.02});
  a.equal(update.status,'REVIEW_REQUIRED');a.notEqual(update.plugin,created.plugin);a.equal(update.replaces.plugin,created.plugin);
  const revision=await call('ck_create_npc',{planId:update.planId,reviewHash:update.reviewHash,operationId:'mage-revision'});
  a.equal(revision.validation.npcs[0].name,'Frostveil Mage Revised');
  a.equal((await call('ck_get_operation_status',{operationId:'guild-mage'})).sha256,created.sha256);
  a.equal((await call('ck_list_npcs',{plugin:created.plugin})).sha256,created.sha256);
  const forbidden=await client.callTool({name:'ck_update_npc',arguments:{plugin:'FrostveilNPCTest.esp',expectedSha256:source.sha256,displayName:'Do not change'}});a.equal(forbidden.isError,true);
  const manual=await call('ck_export_facegen',{plugin:created.plugin,localId:0x800});a.equal(manual.status,'MANUAL_REQUIRED');
  const handoff=await call('ck_prepare_frostveil_import',{plugin:created.plugin});a.equal(handoff.spawnable,false);a.equal(handoff.status,'MANUAL_REQUIRED');
  const invalid=await client.callTool({name:'ck_list_npcs',arguments:{plugin:'../Skyrim.esm'}});a.equal(invalid.isError,true);
  a.equal(tools.tools.length,14);a.ok(tools.tools.every(t=>called.has(t.name)));
  fs.writeFileSync(path.join(work,'protocol-proof.json'),JSON.stringify({server:client.getServerVersion(),tools:tools.tools.map(t=>t.name),called:[...called],progress,created,valid,handoff,stderr},null,2));
  const scan=spawnSync(process.execPath,[path.join(pkg,'tests/g245-native.cjs'),work],{encoding:'utf8',timeout:60000,windowsHide:true,maxBuffer:1024*1024});
  a.equal(scan.status,0,scan.stdout+scan.stderr);a.equal(JSON.parse(scan.stdout.trim().split('\n').at(-1)).g245,'PASS');
 } finally {await client.close();}
});
